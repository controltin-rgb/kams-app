import "server-only";
import { randomUUID } from "node:crypto";
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";

/** Files live outside /public and are only served through an authorised route handler. */
// turbopackIgnore: runtime-only path, keeps output tracing from including the whole project
const ROOT = path.resolve(/* turbopackIgnore: true */ process.env.STORAGE_DIR ?? path.join(/* turbopackIgnore: true */ process.cwd(), "storage"));

export const MAX_UPLOAD_BYTES = 10 * 1024 * 1024;

const signatures: { mime: string; ext: string; test: (b: Buffer) => boolean }[] = [
  { mime: "image/jpeg", ext: "jpg", test: (b) => b[0] === 0xff && b[1] === 0xd8 && b[2] === 0xff },
  { mime: "image/png", ext: "png", test: (b) => b.subarray(0, 8).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a])) },
  { mime: "image/gif", ext: "gif", test: (b) => b.subarray(0, 4).toString("latin1") === "GIF8" },
  { mime: "image/webp", ext: "webp", test: (b) => b.subarray(0, 4).toString("latin1") === "RIFF" && b.subarray(8, 12).toString("latin1") === "WEBP" },
  { mime: "application/pdf", ext: "pdf", test: (b) => b.subarray(0, 5).toString("latin1") === "%PDF-" },
];

/** Detect the real file type from its content (never trust the client-provided type or name). */
export function sniffType(buffer: Buffer) {
  return signatures.find((s) => s.test(buffer)) ?? null;
}

function resolveKey(key: string) {
  const full = path.resolve(ROOT, key);
  // Keys are generated by us, but guard against traversal anyway
  if (!full.startsWith(ROOT + path.sep)) throw new Error("Invalid storage key");
  return full;
}

/** Save under a random name: <yyyy>/<mm>/<uuid>.<ext>. Returns the storage key. */
export async function saveFile(buffer: Buffer, ext: string) {
  const now = new Date();
  const key = path.posix.join(String(now.getUTCFullYear()), String(now.getUTCMonth() + 1).padStart(2, "0"), `${randomUUID()}.${ext}`);
  const full = resolveKey(key);
  await mkdir(path.dirname(full), { recursive: true });
  await writeFile(full, buffer, { flag: "wx" });
  return key;
}

export async function readStoredFile(key: string) {
  return readFile(resolveKey(key));
}

export async function deleteStoredFile(key: string) {
  await rm(resolveKey(key), { force: true });
}
